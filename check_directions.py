NON_ASCII_DASH = re.compile("[‐-―− ]")
failures = []


def check(name, cond, detail=""):
    print(f"  {'PASS' if cond else 'FAIL'}  {name}" + (f"   <-- got: {detail}" if detail and not cond else ""))
    if not cond:
        failures.append(name)


def app_source():
    return open("app.py", encoding="utf-8").read()


def step1():
    print("Step 1 - scraper.py")
    from scraper import _normalise, ascii_lower, normalize_dashes
    check("ascii_lower normalises U+2011 and lowercases", ascii_lower("Cross‑Functional") == "cross-functional")
    check("normalize_dashes keeps case", normalize_dashes("Co—Founder") == "Co-Founder")
    check("normalize_dashes handles None", normalize_dashes(None) == "")
    row = {"site": "indeed", "id": "x1", "title": "PM", "company": "Acme", "company_num_employees": "11 to 50",
           "company_industry": "Software", "company_description": "a" * 900, "description": "text"}
    job = _normalise(row, "pm")
    check("job has company_size", job.get("company_size") == "11 to 50", repr(job.get("company_size")))
    check("job has company_industry", job.get("company_industry") == "Software", repr(job.get("company_industry")))
    check("company_about capped at 600 chars", len(job.get("company_about", "")) == 600)
    empty = _normalise({"site": "linkedin", "title": "PM"}, "pm")
    check("missing company fields become empty strings",
          empty.get("company_size") == "" and empty.get("company_about") == "", repr(empty.get("company_size")))


def step2():
    print("Step 2 - matcher.py: directions (2 live Groq calls)")
    from matcher import CareerDirection, clean_direction, draft_directions, parse_direction
    fields = set(CareerDirection.model_fields)
    check("CareerDirection has all 8 fields", fields == {"role", "caution", "fits_where", "avoid_where", "proof",
                                                        "search_titles", "good_signals", "bad_signals"}, str(fields))
    messy = dict(DIRECTION, role="AI Product‑Manager", good_signals=["Founding", "founding", " seed "],
                 search_titles=["A", "B", "C", "D"], caution="maybe")
    c = clean_direction(messy)
    check("clean_direction fixes dashes", c["role"] == "AI Product-Manager", c["role"])
    check("clean_direction lowercases + dedupes signals", c["good_signals"] == ["founding", "seed"], str(c["good_signals"]))
    check("clean_direction caps search_titles at 3", len(c["search_titles"]) == 3)
    check("clean_direction repairs unknown caution", c["caution"] == "selective", c["caution"])

    t = time.time()
    ds = draft_directions(SAMPLE_RESUME)
    print(f"    drafted {len(ds)} directions in {time.time() - t:.1f}s: "
          + ", ".join(f"{d['role']} [{d['caution']}]" for d in ds))
    check("draft returns 3-5 directions", 3 <= len(ds) <= 5, str(len(ds)))
    check("every direction has 1-3 search titles", all(1 <= len(d["search_titles"]) <= 3 for d in ds))
    all_text = " ".join(str(v) for d in ds for v in d.values())
    check("no typographic dashes left", not NON_ASCII_DASH.search(all_text))

    t = time.time()
    p = parse_direction(USER_SENTENCE, SAMPLE_RESUME)
    print(f"    parsed the example sentence in {time.time() - t:.1f}s: {p['role']} [{p['caution']}]")
    check("parsed caution stays 'careful'", p["caution"] == "careful", p["caution"])
    check("parsed role mentions product", "product" in p["role"].lower(), p["role"])
    check("parsed fits_where mentions seed", "seed" in p["fits_where"].lower(), p["fits_where"])


def step3():
    print("Step 3 - matcher.py: direction-aware matching (3 live Groq calls)")
    from matcher import company_info, direction_text, match_job
    check("direction_text(None) says none set", "none set" in direction_text(None))
    check("direction_text includes avoid_where", DIRECTION["avoid_where"] in direction_text(DIRECTION))
    check("company_info with no fields", company_info({}) == "none provided", company_info({}))
    check("company_info includes employees", "employees: 10,000+" in company_info(ENTERPRISE_JOB))

    ent = match_job(PROFILE, ENTERPRISE_JOB, direction=DIRECTION)
    print(f"    enterprise job: fit={ent['context_fit']} stage={ent['company_stage']} score={ent['score']}")
    check("enterprise job is 'outside'", ent["context_fit"] == "outside", ent["context_fit"])
    check("outside job penalised + flagged", any("Outside your conditions" in f for f in ent["red_flags"]), str(ent["red_flags"]))
    check("result records the direction", ent.get("direction") == "AI Product Manager", repr(ent.get("direction")))

    seed = match_job(PROFILE, SEED_JOB, direction=DIRECTION)
    print(f"    seed job: fit={seed['context_fit']} stage={seed['company_stage']} score={seed['score']}")
    check("seed job 'fits'", seed["context_fit"] == "fits", seed["context_fit"])
    check("seed job scores above enterprise job", seed["score"] > ent["score"], f"{seed['score']} vs {ent['score']}")

    plain = match_job(PROFILE, SEED_JOB)
    check("no direction -> context 'unclear' and still works", plain["context_fit"] == "unclear", plain["context_fit"])


def step4():
    print("Step 4 - matcher.py: title filter + signal pre-rank (offline)")
    from matcher import keyword_score, signal_score, title_relevance
    titles = ["AI Product Manager"]
    check("'Senior Product Manager (AI Agents)' is on-target",
          title_relevance("Senior Product Manager (AI Agents)", titles) >= 0.5)
    check("'Customer Success Manager' is off-target", title_relevance("Customer Success Manager", titles) < 0.5)
    check("'North America Sr. Sales Manager' is off-target",
          title_relevance("North America Sr. Sales Manager", titles) < 0.5)
    check("'Founding Product Lead' is on-target",
          title_relevance("Founding Product Lead", ["Founding Product Manager"]) >= 0.5)
    check("dash variants match", title_relevance("Co‑Founder", ["co-founder"]) == 1.0)
    check("signal_score rewards good signals", signal_score(DIRECTION, SEED_JOB) > 0, str(signal_score(DIRECTION, SEED_JOB)))
    check("signal_score punishes bad signals", signal_score(DIRECTION, ENTERPRISE_JOB) < 0,
          str(signal_score(DIRECTION, ENTERPRISE_JOB)))
    check("signal_score(None, job) == 0", signal_score(None, SEED_JOB) == 0)
    check("keyword_score ranks seed above enterprise with a direction",
          keyword_score(PROFILE, SEED_JOB, DIRECTION) > keyword_score(PROFILE, ENTERPRISE_JOB, DIRECTION))
    check("keyword_score still works without a direction", 0 <= keyword_score(PROFILE, SEED_JOB) <= 100)


def _compiles():
    import py_compile
    try:
        py_compile.compile("app.py", doraise=True)
        check("app.py compiles", True)
        return True
    except py_compile.PyCompileError as e:
        check("app.py compiles", False, str(e)[:300])
        return False


def step5():
    print("Step 5 - app.py: state, helpers, drafting (offline)")
    if not _compiles():
        return
    src = app_source()
    check("no use_container_width (use width='stretch')", "use_container_width" not in src)
    check("no unsafe_allow_html", "unsafe_allow_html" not in src)
    check("no asyncio", "asyncio" not in src)
    for needle in ('"dir_version": 0', "def set_directions", "def terms_from_directions", "def df_to_directions",
                   "def add_own_direction", "def use_directions_for_search", "draft_directions(ss.resume_text",
                   "dir_base=None)"):
        check(f"app.py contains {needle}", needle in src)
    # Run the table <-> directions helpers for real, without starting Streamlit.
    import numpy as np
    import pandas as pd
    from matcher import clean_direction
    ns = {"pd": pd, "clean_direction": clean_direction}
    exec(src[src.index("CAUTION_COLORS = "):src.index("def set_directions")], ns)
    exec(src[src.index("def terms_from_directions"):src.index("def direction_of")], ns)
    df = ns["directions_to_df"]([dict(DIRECTION, use=True)])
    df.loc[0, "use"] = np.False_                                  # unticked in the editor
    df.loc[1] = [None, "Co‑founder", None, None, None, None, "Founding CTO", "Founding", None]  # new row
    out = ns["df_to_directions"](df)
    check("unticked row -> use False (numpy bool handled)", out[0]["use"] is False, repr(out[0]["use"]))
    check("new row -> use True, caution repaired, dash fixed",
          out[1]["use"] is True and out[1]["caution"] == "selective" and out[1]["role"] == "Co-founder", str(out[1]))
    check("row with empty search titles falls back to the role",
          ns["df_to_directions"](ns["directions_to_df"]([dict(DIRECTION, search_titles=[])]))[0]["search_titles"]
          == ["AI Product Manager"])
    mine = dict(DIRECTION, role="Mine", search_titles=["X1", "X2", "X3"])
    many = [dict(DIRECTION, role=f"AI {i}", search_titles=[f"T{i}a", f"T{i}b"]) for i in range(4)] + [mine]
    terms = ns["terms_from_directions"](many)
    check("terms: max 6, your newest row first", len(terms) == 6 and terms[:2] == ["X1", "X2"], str(terms))
    check("terms skip unticked rows", "X1" not in ns["terms_from_directions"]([dict(mine, use=False)]))


